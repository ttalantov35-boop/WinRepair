#!/usr/bin/env python3
"""Merge numbered translations (lang/tr/*.txt: `N|English`, <sp> = space marker) with lang/keys.txt into lang/en.txt.
Run from the project root: python3 tools/i18n_merge.py"""
import glob, os
keys = {}
for line in open('lang/keys.txt', encoding='utf-8'):
    line = line.rstrip('\n')
    if '\t' in line:
        n, k = line.split('\t', 1)
        keys[int(n)] = k
out, seen = [], set()
for p in sorted(glob.glob('lang/tr/*.txt')):
    for line in open(p, encoding='utf-8'):
        line = line.rstrip('\n').rstrip('\r')
        if not line or line.startswith('#') or '|' not in line:
            continue
        n, en = line.split('|', 1)
        if not n.strip().isdigit():
            continue
        n = int(n)
        en = en.replace('<sp>', ' ')
        if n in keys and en != '' and n not in seen:
            seen.add(n)
            out.append(f'{keys[n]} ==> {en}')
import os
if os.path.exists('lang/extra.txt'):
    for line in open('lang/extra.txt', encoding='utf-8'):
        line = line.rstrip('\n').rstrip('\r')
        if line and not line.startswith('#') and ' ==> ' in line:
            out.append(line)
hdr = '# WinRepair English dictionary: `Russian text ==> English text`; {} = wildcard; generated by tools/i18n_merge.py from lang/keys.txt + lang/tr/*.txt\n'
open('lang/en.txt', 'w', encoding='utf-8').write(hdr + '\n'.join(out) + '\n')
print(f'{len(out)} of {len(keys)} keys translated ({100*len(out)//max(1,len(keys))}%)')
